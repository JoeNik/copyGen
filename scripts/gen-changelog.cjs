#!/usr/bin/env node
/**
 * Generate src/lib/changelog.ts from the git log.
 *
 * Baked in at commit time rather than fetched from the GitHub API at runtime:
 * the changelog then works offline, needs no token, and can't be rate-limited
 * (unauthenticated GitHub API allows only 60 requests/hour per IP, and the
 * landing page has no session to borrow a token from).
 *
 * Invoked by .githooks/pre-commit alongside the version bump.
 */
const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const root = path.resolve(__dirname, "..");
const outPath = path.join(root, "src", "lib", "changelog.ts");
const MAX_ENTRIES = 40;

// Control characters as field/record separators — they can't occur in a commit
// message, so splitting is unambiguous.
const SEP = "\x1f";
const ENTRY = "\x1e";

function git(args) {
  return execFileSync("git", args, { cwd: root, encoding: "utf8", maxBuffer: 8 * 1024 * 1024 });
}

let raw = "";
try {
  raw = git(["log", `-${MAX_ENTRIES}`, "--no-merges", `--format=%h${SEP}%aI${SEP}%s${SEP}%b${ENTRY}`]);
} catch {
  // No git history available (e.g. shallow CI checkout) — emit an empty log
  // rather than failing the build.
  raw = "";
}

const entries = raw
  .split(ENTRY)
  .map((chunk) => chunk.trim())
  .filter(Boolean)
  .map((chunk) => {
    const [hash = "", date = "", subject = "", body = ""] = chunk.split(SEP);
    // Keep the body's bullet lines; drop trailers and generated footers.
    const details = body
      .split("\n")
      .map((l) => l.trim())
      .filter(
        (l) =>
          l &&
          !/^Co-Authored-By:/i.test(l) &&
          !/^Signed-off-by:/i.test(l) &&
          !/Generated with \[?Claude/i.test(l)
      )
      .map((l) => l.replace(/^[-*]\s*/, ""));
    return {
      hash: hash.trim(),
      date: date.trim().slice(0, 10),
      subject: subject.trim(),
      details,
    };
  })
  .filter((e) => e.hash && e.subject);

const header = `// AUTO-GENERATED by scripts/gen-changelog.cjs (pre-commit hook). Do not edit.

export interface ChangelogEntry {
  hash: string;
  /** YYYY-MM-DD */
  date: string;
  subject: string;
  /** Body lines, bullet markers already stripped */
  details: string[];
}

export const CHANGELOG: ChangelogEntry[] = `;

fs.writeFileSync(outPath, header + JSON.stringify(entries, null, 2) + ";\n");

if (process.env.BUMP_VERSION_STAGE !== "0") {
  try {
    git(["add", "src/lib/changelog.ts"]);
  } catch {
    /* not inside a commit — leave it unstaged */
  }
}

console.log(`[gen-changelog] ${entries.length} entries`);
